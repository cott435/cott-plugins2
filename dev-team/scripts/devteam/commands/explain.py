"""Explain the pipelines in plain words: what each is for, how it runs and what each step does, from pipelines.md."""
from __future__ import annotations

import re
import sys

from .. import edit, md, model

DIR = "docs/explained"
NOTE = ("Generated by `dt explain --write` from the pipelines docs, for reading. Don't edit it: change the pipelines "
        "doc and run `dt explain --write` again.")


def add_arguments(parser):
    parser.add_argument("targets", nargs="*", help="PL-NN IDs or package names (default: every pipeline)")
    parser.add_argument("--write", action="store_true", help=f"write {DIR}/<package>.md (system.md for system "
                                                             "pipelines) instead of printing")


def all_pipelines(repo) -> list[model.Pipeline]:
    return [p for d in repo.docs("architecture", "pipelines") for p in model.pipelines(d)]


def group(p: model.Pipeline) -> str:
    return "system" if p.is_system else (p.package or "system")


def requirement(repo, id_: str, width: int = 90) -> str:
    """A spec requirement's own words, shortened: `INGST-06 "Every run is recorded…"`."""
    d = repo.lookup(id_, archive=False)
    if d is None or d.retired or d.how != "requirement":
        return id_
    text = md.strip_md(re.sub(rf"^\s*[-*]\s+\*\*{re.escape(id_)}\*\*\s*", "", d.doc.lines[d.start])).strip()
    if len(text) > width:
        text = text[:width].rsplit(" ", 1)[0].rstrip(",;:") + "…"
    return f'{id_} "{text}"'


def serves(repo, ids: list[str], most: int = 3) -> str:
    shown = [requirement(repo, i) for i in ids[:most]]
    more = f" and {len(ids) - most} more" if len(ids) > most else ""
    return "; ".join(shown) + more


def render(repo, p: model.Pipeline) -> list[str]:
    owners = {q.id: q for q in all_pipelines(repo)}
    out = [f"## {p.id}: {md.strip_md(p.title)}", ""]
    purpose = md.strip_md(p.fields.get("Purpose", "")).strip()
    covers = p.covers
    out.append(f"**What it's for:** {purpose}" if purpose
               else f"**What it's for:** (no Purpose line yet) it serves {serves(repo, covers)}")
    run = [f"**How it runs:** `{p.trigger}`" if p.trigger else "**How it runs:** called from other code"]
    part = md.strip_md(p.fields.get("Part of", "")).strip()
    if part:
        whole = owners.get(part)
        run.append(f"as one segment of {part}" + (f" ({md.strip_md(whole.title)})" if whole else ""))
    out += [" · ".join(run), ""]
    segments = [q for q in owners.values() if md.strip_md(q.fields.get("Part of", "")).strip() == p.id]
    if not p.steps:
        hops = [md.strip_md(x).strip() for x in p.doc.lines[p.start + 1:p.end] if re.match(r"^\d+\.\s", x)]
        if hops:
            out += ["**How it flows between packages:**", ""] + hops + [""]
        if segments:
            out.append("**Its pieces, each explained on its package's page:** "
                       + ", ".join(f"{q.id} {md.strip_md(q.title)} ({group(q)})" for q in segments))
    else:
        out += ["**What it does, in order:**", ""]
    n = 0
    for i, s in enumerate(p.steps):
        io = re.sub(r"\s*(→|->)\s*", " → ", md.strip_md(s.io)).strip()
        what = md.strip_md(s.spine).strip()
        if s.is_class:
            out.append(f"      - **{s.name}** ({s.owner}): {what}" + (f" · takes {io}" if io else ""))
            continue
        n += 1
        out.append(f"{n}. **{s.name}** ({s.owner}): {what}")
        if io:
            out.append(f"   - takes and gives: {io}")
        if s.covers:
            out.append(f"   - serves: {serves(repo, s.covers)}")
        if i + 1 < len(p.steps) and p.steps[i + 1].is_class:
            out.append("   - builds one of these, which the pipeline then drives:")
    out.append("")
    return out


def page(repo, name: str, pipes: list[model.Pipeline]) -> str:
    title = "System pipelines" if name == "system" else f"{name} pipelines"
    lines = [f"# {title}, explained", "", NOTE, ""]
    for p in pipes:
        lines += render(repo, p)
    return "\n".join(lines).rstrip() + "\n"


def pages(repo) -> dict[str, str]:
    """Every page `--write` would write, by path."""
    by: dict[str, list[model.Pipeline]] = {}
    for p in all_pipelines(repo):
        by.setdefault(group(p), []).append(p)
    return {f"{DIR}/{name}.md": page(repo, name, pipes) for name, pipes in sorted(by.items())}


def run(args, repo) -> int:
    pipes = all_pipelines(repo)
    if args.write:
        if args.targets:
            print("dt explain: --write writes every package's page; give no targets", file=sys.stderr)
            return 2
        written = pages(repo)
        for rel, text in written.items():
            path = repo.root / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            edit.write_text(path, text)
        print("\n".join(written) or "dt explain: no pipelines")
        return 0
    chosen = [p for p in pipes if not args.targets or p.id in args.targets or group(p) in args.targets]
    missing = [t for t in args.targets if not any(p.id == t or group(p) == t for p in pipes)]
    for t in missing:
        print(f"dt explain: {t} is no pipeline or package", file=sys.stderr)
    if not chosen:
        return 1
    print("\n".join(line for p in chosen for line in render(repo, p)).rstrip())
    return 1 if missing else 0
