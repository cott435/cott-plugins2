"""The Workflow script `dt build workflow` emits (build-phase.md §5, the A3-WF eval arm).

The script drives one stretch of a milestone build the way the build skill's loop (skills/build/references/loop.md)
does, with dt still the decider: it never holds the plan's order. A low-effort dispatch agent runs
`dt ready --reserve --cap N --json` in the main checkout and returns its rows; each row becomes an agent of its
`agent_type` in a worktree; each finish gets a low-effort land agent (`dt land`, or `dt finding --from` for a review);
every landing is followed by another dispatch for the slots it freed. Calls that touch the main checkout (dispatch,
land, finding, release, status) run one at a time. When `dt ready` lists nothing and nothing is running, a status
agent runs `dt build status` and the script returns a summary, so the driver handles the stop as escalation.md says
and runs the workflow again.

A Workflow script has no shell and no filesystem, so every dt call is an agent; the dt path, the project root and
the reviews folder are written into the script as absolute paths.
"""
from __future__ import annotations

import json
import shlex
from pathlib import Path

from . import buildstate as bs
from . import dispatch

TASK, ROLE = "@@TASK@@", "@@ROLE@@"

TEMPLATE = r"""export const meta = {
  name: 'dt-build-__MILESTONE__',
  description: 'Build __MILESTONE__: dispatch what dt ready lists, land each finish with dt land, until nothing is ready or running',
  whenToUse: 'Emitted by dt build workflow __MILESTONE__; the build driver runs it and runs it again after each stop',
  phases: [
    { title: 'Dispatch', detail: 'dt ready --reserve, one low-effort agent per call' },
    { title: 'Build', detail: 'one agent per ready half or review, each in its own worktree' },
    { title: 'Land', detail: 'dt land or dt finding --from, one at a time in the main checkout' },
    { title: 'Status', detail: 'dt build status once nothing is ready or running' },
  ],
}

// Generated by `dt build workflow`: edit dt, not this file. The plan's order lives in dt; this script only
// spawns what `dt ready` lists and lands what finishes.
const DT = __DT__                    // dt in the main checkout
const CAP = __CAP__
const REVIEWS = __REVIEWS__          // dt-build/reviews, where `dt build submit-review` puts findings files
const BUILDER_PROMPT = __BUILDER_PROMPT__
const AGENT_TYPE = __AGENT_TYPE__

const NULLABLE = { type: ['string', 'null'] }
const READY_SCHEMA = {
  type: 'object',
  properties: {
    rows: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          id: { type: 'string' }, role: { type: 'string' }, agent_type: { type: 'string' },
          prompt: { type: 'string' }, checkpoint: { type: 'string' }, pkg: { type: 'string' },
        },
        required: ['id', 'role'],
      },
    },
    holds: { type: 'array', items: { type: 'string' } },
    all_landed: { type: 'boolean' },
    error: { type: 'string' },
  },
  required: ['rows', 'holds', 'all_landed'],
}
const LAND_SCHEMA = {
  type: 'object',
  properties: { landed: { type: 'boolean' }, reject: NULLABLE, kind: NULLABLE, detail_file: NULLABLE, error: { type: 'string' } },
  required: ['landed'],
}
const FINDING_SCHEMA = {
  type: 'object',
  properties: {
    outcome: { type: 'string' }, findings: { type: 'array', items: { type: 'string' } },
    critical: { type: 'array', items: { type: 'string' } }, error: { type: 'string' },
  },
  required: ['findings', 'critical'],
}
const HALF = {
  type: 'object',
  properties: { id: { type: 'string' }, role: { type: 'string' }, why: { type: 'string' } },
  required: ['id', 'why'],
}
const STATUS_SCHEMA = {
  type: 'object',
  properties: {
    progress: { type: 'string' },
    all_landed: { type: 'boolean' },
    go_current: { type: ['boolean', 'null'] },
    next_checkpoint: NULLABLE,
    holds: { type: 'array', items: { type: 'string' } },
    blocked: { type: 'array', items: HALF },
    held: { type: 'array', items: HALF },
    escalations: {
      type: 'array',
      items: {
        type: 'object',
        properties: { task: { type: 'string' }, role: { type: 'string' }, kind: { type: 'string' }, type: NULLABLE, why: { type: 'string' } },
        required: ['task', 'kind'],
      },
    },
    critical_open: { type: 'array', items: { type: 'string' } },
    claims: { type: 'array', items: { type: 'string' } },
    error: { type: 'string' },
  },
  required: ['progress', 'all_landed', 'holds', 'blocked', 'held', 'escalations', 'critical_open'],
}

const ONE_COMMAND = 'Run exactly one Bash command, alone, in your current directory (the main checkout), with the Bash ' +
  'timeout at its maximum (600000 ms), and wait for it to finish: '
const NOTHING_ELSE = ' Run nothing else: never retry it, never fix anything, never read the files it names.'

const DISPATCH_PROMPT = 'You are the dispatch step of a dt build. ' + ONE_COMMAND +
  '`' + DT + ' ready --reserve --cap ' + CAP + ' --json`. It prints one JSON object. Return every element of its ' +
  '`rows` with `id`, `role`, `agent_type`, `checkpoint` and `pkg` when present, and `prompt` copied verbatim, ' +
  'character for character; then its `holds` and `all_landed`. If it fails or prints no JSON, return empty `rows` ' +
  'and `holds`, `all_landed` false, and its output in `error`.' + NOTHING_ELSE +
  ' The command reserves every row it lists, so running it twice loses work.'

function landPrompt(cmd) {
  return 'You are the land step of a dt build. ' + ONE_COMMAND + '`' + cmd + '`. It prints one JSON object; return ' +
    'its `landed`, `reject`, `kind` and `detail_file` as printed (null stays null), and its `error` if it has one. ' +
    'If it prints no JSON, return landed false and its output in `error`.' + NOTHING_ELSE
}

function findingPrompt(cmd) {
  return 'You are the review-recording step of a dt build. ' + ONE_COMMAND + '`' + cmd + '`. It prints one JSON ' +
    'object; return its `outcome`, `findings` and `critical` lists, and its `error` if it has one (then the lists are ' +
    'empty). If it prints no JSON, return empty lists and its output in `error`.' + NOTHING_ELSE
}

const STATUS_PROMPT = 'You are the status step of a dt build. ' + ONE_COMMAND + '`' + DT + ' build status`. It ' +
  'prints one JSON object. Return: `progress`, `all_landed`, `go_current`; `next_checkpoint` as its `checkpoint` ' +
  'field (null when it is null); `holds`; `blocked` and `held` as {id, role, why}; `escalations` as {task, role, ' +
  'kind, type, why}; `critical_open` as every id in the `critical_open` list of each element of `reviews`; `claims` ' +
  'as the `id` of each element of `claims`. Copy, never summarise. If it fails, put its output in `error`.' + NOTHING_ELSE

function builderPrompt(id, role) {
  return BUILDER_PROMPT.split('@@TASK@@').join(id).split('@@ROLE@@').join(role)
}

// The builder's last non-empty line: DONE <task> <role> or STOPPED <task> <role>: ...; anything else is a harness failure.
function statusLine(text, id, role) {
  if (typeof text !== 'string') return null
  const lines = text.split('\n').map(s => s.trim().replace(/^[`*]+|[`*]+$/g, '').trim()).filter(Boolean)
  const m = (lines[lines.length - 1] || '').match(/^(DONE|STOPPED)\s+(\S+?)\s+([a-z]+)\b/)
  return m && m[2] === id && m[3] === role ? m[1] : null
}

// Every call that touches the main checkout runs alone, in the order it was asked for.
let chain = Promise.resolve()
function serial(fn) {
  const p = chain.then(fn)
  chain = p.then(() => {}, () => {})
  return p
}

const running = new Set()
const landings = []
const reviews = []
const reviewFailures = {}
const notes = []
let dispatches = 0

async function dispatchReady() {
  const r = await serial(() => {
    dispatches += 1
    return agent(DISPATCH_PROMPT, { label: 'dispatch ' + dispatches, phase: 'Dispatch', schema: READY_SCHEMA, effort: 'low' })
  })
  if (!r) { notes.push('a dispatch agent returned nothing'); return }
  if (r.error) notes.push('dt ready: ' + r.error)
  const rows = r.rows || []
  if (rows.length) log('dispatch: ' + rows.map(x => x.id + ' ' + x.role).join(', '))
  for (const row of rows) start(row)
}

function start(row) {
  if (!/^[A-Za-z0-9_.-]+$/.test(row.id || '') || !/^[a-z]+$/.test(row.role || '')) {
    notes.push('a dispatch row that is not a half or a review was skipped: ' + JSON.stringify(row).slice(0, 200))
    return
  }
  const p = runRow(row)
    .catch(e => { notes.push(row.id + ' ' + row.role + ': ' + ((e && e.message) || String(e))) })
    .finally(() => running.delete(p))
  running.add(p)
}

async function runRow(row) {
  try {
    if (row.role === 'reviewer') await review(row)
    else await buildHalf(row)
  } finally {
    await dispatchReady()
  }
}

async function buildHalf(row) {
  const agentType = AGENT_TYPE[row.role] || row.agent_type
  const text = await agent(builderPrompt(row.id, row.role),
    { label: row.id + ' ' + row.role, phase: 'Build', agentType: agentType, isolation: 'worktree' })
  const line = statusLine(text, row.id, row.role)
  const cmd = DT + ' land ' + row.id + ' --role ' + row.role + (line ? '' : ' --harness')
  const r = await serial(() => agent(landPrompt(cmd),
    { label: 'land ' + row.id + ' ' + row.role, phase: 'Land', schema: LAND_SCHEMA, effort: 'low' }))
  const rec = {
    id: row.id, role: row.role, status: line || 'none', landed: Boolean(r && r.landed),
    reject: r ? (r.reject || null) : 'land agent returned nothing', kind: (r && r.kind) || null,
    detail_file: (r && r.detail_file) || null,
  }
  if (r && r.error) rec.error = r.error
  landings.push(rec)
  log(row.id + ' ' + row.role + ': ' + (rec.landed ? 'landed' : 'reject ' + rec.reject + (rec.kind ? ' (' + rec.kind + ')' : '')))
}

async function review(row) {
  const dot = row.id.indexOf('.')
  const checkpoint = row.checkpoint || row.id.slice(0, dot)
  const pkg = row.pkg || row.id.slice(dot + 1)
  if (!row.prompt) {
    notes.push(row.id + ': the dispatch returned no prompt for this review; reserved, not spawned')
    return
  }
  await agent(row.prompt, { label: row.id + ' reviewer', phase: 'Build', agentType: AGENT_TYPE.reviewer, isolation: 'worktree' })
  const cmd = DT + ' finding --from ' + REVIEWS + '/' + row.id + '.md --checkpoint ' + checkpoint + ' --pkg ' + pkg
  const r = await serial(() => agent(findingPrompt(cmd),
    { label: 'record ' + row.id, phase: 'Land', schema: FINDING_SCHEMA, effort: 'low' }))
  if (r && !r.error) {
    reviews.push({ review: row.id, outcome: r.outcome || null, findings: r.findings.length, critical: r.critical })
    log(row.id + ' review: ' + r.findings.length + ' findings, ' + r.critical.length + ' Critical')
    return
  }
  // No findings file: release the reservation and let dt list the review again; a second time is a stop.
  reviewFailures[row.id] = (reviewFailures[row.id] || 0) + 1
  log(row.id + ' review: not recorded (' + (r ? r.error : 'no result') + ')')
  if (reviewFailures[row.id] < 2) {
    await serial(() => agent('You are the release step of a dt build. ' + ONE_COMMAND + '`' + DT + ' build release ' +
      row.id + ' reviewer`. Return its output.' + NOTHING_ELSE,
      { label: 'release ' + row.id, phase: 'Land', effort: 'low' }))
  }
}

await dispatchReady()
while (running.size) await Promise.race(Array.from(running))

const st = await serial(() => agent(STATUS_PROMPT, { label: 'status', phase: 'Status', schema: STATUS_SCHEMA, effort: 'low' }))
const s = st || {}
return {
  milestone: '__MILESTONE__',
  all_landed: Boolean(s.all_landed),
  exit_ready: Boolean(s.all_landed) && !s.next_checkpoint,
  progress: s.progress || null,
  next_checkpoint: s.next_checkpoint || null,
  go_current: s.go_current === undefined ? null : s.go_current,
  holds: s.holds || [],
  blocked: s.blocked || [],
  held: s.held || [],
  escalations: s.escalations || [],
  critical_open: s.critical_open || [],
  claims: s.claims || [],
  review_failures: Object.keys(reviewFailures).filter(k => reviewFailures[k] >= 2),
  landings: landings,
  reviews: reviews,
  notes: st ? (s.error ? notes.concat(['dt build status: ' + s.error]) : notes) : notes.concat(['the status agent returned nothing']),
}
"""


def script(root: Path, milestone: str, cap: int) -> str:
    """The Workflow script for `milestone`'s build in the project at `root` (its main checkout)."""
    dt = shlex.join(["python3", str(bs.DT_PY), "--root", str(root)])
    reviews = bs.State(root).path("reviews")
    values = {
        "__DT__": json.dumps(dt),
        "__CAP__": str(int(cap)),
        "__REVIEWS__": json.dumps(shlex.quote(str(reviews))),
        "__BUILDER_PROMPT__": json.dumps(dispatch.builder_prompt(TASK, ROLE)),
        "__AGENT_TYPE__": json.dumps({r: dispatch.agent_type(r) for r in bs.ROLES} | {"reviewer": "reviewer"}),
        "__MILESTONE__": milestone,
    }
    out = TEMPLATE
    for k, v in values.items():
        out = out.replace(k, v)
    return out
