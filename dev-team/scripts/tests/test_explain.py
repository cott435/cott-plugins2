"""`dt explain`: the pipelines in plain words, and the `explain-stale` lint, on copies of fixtures/quant."""
from __future__ import annotations

import unittest

from dt_helpers import FixtureCopy

from devteam.commands import lint  # noqa: E402
from devteam.repo import Repo  # noqa: E402

PIPES = "docs/packages/quant/pipelines.md"


class ExplainTest(FixtureCopy):
    def test_one_pipeline(self):
        code, out, _ = self.dt("explain", "PL-01")
        self.assertEqual(code, 0)
        self.assertTrue(out.startswith("## PL-01: Load prices\n"))
        self.assertIn("**What it's for:** (no Purpose line yet) it serves DATA-01 \"A command loads daily prices "
                      "for a date range and universe.\"", out)
        self.assertIn("1. **read_raw** (data): read a synthetic CSV\n   - takes and gives: dates → RawPrices\n", out)
        self.assertIn('2. **apply_universe** (data): static universe, no delistings', out)
        self.assertNotIn("## PL-02", out)

    def test_purpose_leads(self):
        self.replace(PIPES, "## PL-01: Load prices\n", "## PL-01: Load prices\n**Purpose:** prices you can trust, "
                     "one command away\n")
        out = self.dt("explain", "PL-01")[1]
        self.assertIn("**What it's for:** prices you can trust, one command away\n", out)

    def test_library_classes_sit_under_their_factory(self):
        self.replace(PIPES, "| 2 | `apply_universe` |",
                     "| 2 | `CsvSource` | data.sources | path → Source | read one file | DATA-01 |\n"
                     "| 3 | `apply_universe` |")
        out = self.dt("explain", "PL-01")[1]
        self.assertIn("   - builds one of these, which the pipeline then drives:\n"
                      "      - **CsvSource** (data.sources): read one file · takes path → Source\n"
                      "2. **apply_universe**", out)

    def test_by_package_and_unknown(self):
        out = self.dt("explain", "quant")[1]
        self.assertEqual([l for l in out.splitlines() if l.startswith("## PL-")][:3],
                         ["## PL-01: Load prices", "## PL-02: Covariance report", "## PL-03: Min-variance backtest"])
        self.assertEqual(self.dt("explain", "PL-99")[0], 1)

    def test_write_and_stale(self):
        code, out, _ = self.dt("explain", "--write")
        self.assertEqual((code, out.strip()), (0, "docs/explained/quant.md"))
        page = self.read("docs/explained/quant.md")
        self.assertTrue(page.startswith("# quant pipelines, explained\n\nGenerated by `dt explain --write`"))
        stale = lambda: [p.path for p in lint.lint(Repo(self.root)) if p.code == "explain-stale"]
        self.assertEqual(stale(), [])
        self.replace(PIPES, "read a synthetic CSV", "read the vendor's CSV")
        self.assertEqual(stale(), ["docs/explained/quant.md"])
        self.dt("explain", "--write")
        self.assertEqual(stale(), [])
        self.write("docs/explained/gone.md", "old\n")
        self.assertEqual(stale(), ["docs/explained/gone.md"])
        self.assertEqual(lint.SEVERITY["explain-stale"], "W")
        self.assertEqual(self.dt("explain", "PL-01", "--write")[0], 2)


if __name__ == "__main__":
    unittest.main()
