#!/usr/bin/env bash
# One entry point for every quality check. Hooks call it; so do CI and people.
# Written by dev-team2 build-setup. Change it through build-setup (Revise), not by hand:
# CONSTRAINTS.md names the rule each step enforces.
#
#   scripts/check.sh fast FILE...        per edit, instant               (PostToolUse: tester, implementer)
#   scripts/check.sh collect             tester's finish gate            (Stop: tester)
#   scripts/check.sh gate [--pkg ID]     implementer's finish gate       (Stop: implementer and solo; dt land)
#   scripts/check.sh full [--pkg ID]     checkpoints, CI                 (reviewer)
#   scripts/check.sh full --exit         the milestone exit: also no interface stub left
#   scripts/check.sh protected           print the protected-path globs  (path_guard.sh deny --protected)
#
# The base is refs/worktree/checks-base, one per worktree (dt claim sets it in a builder's worktree,
# dt land in the main checkout), else HEAD.
#
# tests/contracts/** in the protected list means the boundary contracts frozen at the base (CR-09);
# a contract folder new since the base belongs to the interface task freezing it, which may write it,
# and so does a frozen folder the task's .claude/.task_writes names (a re-freeze interface task).
#
# collect runs the intent tests changed since the base and fails unless they are red for the right
# reason (scripts/red_check.py): AssertionError or an interface stub's NotImplementedError, never
# an ImportError or AttributeError.
#
# --pkg ID runs the tests of package ID and of every package that depends on it (multi-package:
# deptry too); gate and full also run tests/contracts, whole, when it exists. Lint, types, size
# and boundaries always cover the whole repo; they take seconds.
# FILE paths are absolute or relative to the project root.
# Prints every failure (it does not stop at the first) and exits 1 if any step failed.
set -u
cd "$(dirname "$0")/.." || exit 1   # hooks may run from another directory
export NO_COLOR=1                   # plain output for the agent reading it

# ---- Generated by build-setup. Do not edit by hand. ----------------------------------------
# The protected list (CONSTRAINTS.md, "Roles and protected paths"). One list serves as git
# pathspecs here and as path_guard.sh globs; in both, * also matches /.
PROTECTED=({{protected_globs}})
SRC_DIRS=({{src_dirs}})            # single package: src · multi-package: packages/<id>/src ...
PACKAGES_DIR="{{packages_dir}}"    # empty for a single package; multi-package: packages
TYPE_GATE="{{type_gate}}"          # mypy | pyright: the type checker that gates (CR-23); full runs both

# A package (or, in a single package, a component) and every package that depends on it,
# from the architecture's dependency rules.
pkg_scope() {
  case "$1" in
{{pkg_scope_cases}}
    *) return 1 ;;
  esac
}

# Non-Python parts (CONSTRAINTS.md names them): their own check commands, run in gate and full.
other_parts() {
  : # e.g. step npm --prefix web run check
}
# ---------------------------------------------------------------------------------------------

mode="${1:-gate}"
shift || true
pkg=""
exit_check=()
args=()
while [ $# -gt 0 ]; do
  case "$1" in
    --pkg) pkg="${2:-}"; shift 2 || shift ;;
    --exit) exit_check=(--exit); shift ;;
    *) args+=("$1"); shift ;;
  esac
done

if [ -n "$pkg" ] && ! pkg_scope "$pkg" >/dev/null; then
  echo "unknown package '$pkg' (see pkg_scope in scripts/check.sh)" >&2
  exit 64
fi

rc=0
failed=()

# A step that is not a Python tool (a script, git, another toolchain).
step() {
  echo "-> $*" >&2
  "$@" || { rc=1; failed+=("$*"); }
}

# A tool from the project's locked environment, never whatever is first on PATH.
run() {
  echo "-> $*" >&2
  uv run --frozen --quiet "$@" || { rc=1; failed+=("$*"); }
}

# A measured check that fails only at the milestone exit: it prints its findings, and the reviewer
# records them, but a mid-milestone run passes.
report() {
  echo "-> $* (reported; fails only with --exit)" >&2
  uv run --frozen --quiet "$@" || echo "(reported, not failing: $*)" >&2
}

# pytest exits 5 when it collects nothing. That is fine for gate and full on a project with no
# tests yet; collect calls pytest through run() so an empty tests/intent fails.
run_tests() {
  echo "-> pytest $*" >&2
  uv run --frozen --quiet pytest "$@"
  local status=$?
  [ "$status" -eq 5 ] && { echo "(no tests collected)" >&2; return; }
  [ "$status" -eq 0 ] || { rc=1; failed+=("pytest $*"); }
}

# The commit this task started from: refs/worktree/checks-base, set per worktree by `dt claim` (and
# by `dt land` in the main checkout). Without it, HEAD, which misses changes already committed.
BASE_REF="refs/worktree/checks-base"
base_commit() {
  git rev-parse -q --verify "$BASE_REF" 2>/dev/null || git rev-parse -q --verify HEAD 2>/dev/null
}

# A boundary contract is frozen once its folder exists at the base (CR-09): each folder under
# tests/contracts/ at the base, and any file directly in it. A folder new since the base is the
# interface task freezing it, so that task may write it; the next task's base freezes it. A frozen
# folder the task's .claude/.task_writes names (from its Writes:, by dt claim) is a re-freeze
# interface task's, so it is open to that task; dt land checks the Writes: against the plan.
CONTRACTS_GLOB="tests/contracts/**"
claimed_contract() {
  local line
  [ -s .claude/.task_writes ] || return 1
  while IFS= read -r line; do
    line="${line%%[[:space:]]}"
    line="${line%/}"; line="${line%/\*\*}"
    [ "$line" = "$1" ] && return 0
  done <.claude/.task_writes
  return 1
}
frozen_contracts() {
  local base meta path
  base=$(base_commit) || return 0
  git ls-tree "$base" -- tests/contracts/ 2>/dev/null | while IFS=$'\t' read -r meta path; do
    case "$meta" in
      *" tree "*) claimed_contract "$path" || echo "$path/**" ;;
      *) echo "$path" ;;
    esac
  done
}

# The protected list as enforced: PROTECTED, with tests/contracts/** narrowed to the frozen contracts.
protected_globs() {
  local g
  for g in "${PROTECTED[@]}"; do
    if [ "$g" = "$CONTRACTS_GLOB" ]; then frozen_contracts; else echo "$g"; fi
  done
}

# Fail if anything matching the given pathspecs changed since the base, untracked files included.
unchanged_since_base() {
  local label="$1" base new
  shift
  echo "-> $label unchanged since $(git rev-parse -q --verify "$BASE_REF" >/dev/null 2>&1 && echo "$BASE_REF" || echo HEAD)" >&2
  if ! base=$(base_commit); then
    echo "no commit to compare against: commit the tester's work first" >&2
    rc=1; failed+=("$label: no commit"); return
  fi
  git --no-pager diff --exit-code --stat "$base" -- "$@" >&2 || { rc=1; failed+=("$label changed"); }
  new=$(git ls-files --others --exclude-standard -- "$@")
  if [ -n "$new" ]; then
    printf 'new untracked files in %s:\n%s\n' "$label" "$new" >&2
    rc=1; failed+=("$label changed")
  fi
}

# The tester may change tests/intent only. Docs and plans are the plugin's business, not this check's.
only_intent_changed() {
  local specs=(tests "${SRC_DIRS[@]}" "${PROTECTED[@]}")
  [ -n "$PACKAGES_DIR" ] && specs+=("$PACKAGES_DIR")
  unchanged_since_base "files outside tests/intent" "${specs[@]}" ':(exclude)tests/intent'
}

# The intent test files the tester changed since the base, committed or not.
changed_intent_tests() {
  local base
  base=$(base_commit) || return 0
  { git diff --relative --name-only --diff-filter=d "$base" -- 'tests/intent/*.py'
    git ls-files --others --exclude-standard -- 'tests/intent/*.py'; } | sort -u |
    while IFS= read -r f; do case "${f##*/}" in test_*|*_test.py) echo "$f" ;; esac; done
}

# Test directories for this run: all of them, or the --pkg scope; tests/contracts always whole.
test_dirs() {
  local scope="" d p
  [ -n "$pkg" ] && scope=$(pkg_scope "$pkg")
  for d in tests/intent tests/unit; do
    if [ -z "$scope" ]; then
      [ -d "$d" ] && echo "$d"
    else
      for p in $scope; do [ -d "$d/$p" ] && echo "$d/$p"; done
    fi
  done
  [ -d tests/contracts ] && echo tests/contracts
}

# deptry checks what each package imports against what it declares.
dependencies() {
  local p scope
  if [ -z "$PACKAGES_DIR" ]; then
    run deptry . --no-ansi
    return
  fi
  if [ -n "$pkg" ]; then
    scope=$(pkg_scope "$pkg")
  else
    scope=$(cd "$PACKAGES_DIR" && for d in */pyproject.toml; do [ -f "$d" ] && dirname "$d"; done)
  fi
  for p in $scope; do
    echo "-> deptry $PACKAGES_DIR/$p" >&2
    (cd "$PACKAGES_DIR/$p" && uv run --frozen --quiet deptry . --no-ansi) || { rc=1; failed+=("deptry $PACKAGES_DIR/$p"); }
  done
}

static_checks() {
  run ruff check --ignore-noqa .   # exceptions go in per-file-ignores, which is protected (CR-01)
  run ruff format --check .
  run "$TYPE_GATE"
  run python scripts/check_size.py "${SRC_DIRS[@]}"
  dependencies
  run lint-imports --no-logo
}

case "$mode" in
  fast)
    # Only Python files, only the files just edited. Fixes what it can in place.
    files=()
    for f in ${args[@]+"${args[@]}"}; do [[ $f == *.py ]] && files+=("$f"); done
    [ ${#files[@]} -eq 0 ] && exit 0
    run ruff check --fix --quiet "${files[@]}"
    run ruff format --quiet "${files[@]}"
    run typos "${files[@]}"
    run python scripts/check_size.py "${files[@]}"
    ;;
  collect)
    if [ ! -d tests/intent ]; then
      echo "tests/intent does not exist: write the intent tests there" >&2
      exit 1
    fi
    run ruff check --ignore-noqa tests/intent
    run ruff format --check tests/intent
    run typos tests/intent
    run pytest tests/intent --collect-only -q --no-cov
    changed=()
    while IFS= read -r f; do changed+=("$f"); done < <(changed_intent_tests)
    run python scripts/red_check.py ${changed[@]+"${changed[@]}"}
    step bash scripts/floor_guard.sh
    only_intent_changed
    ;;
  gate)
    static_checks
    other_parts
    dirs=$(test_dirs)
    # shellcheck disable=SC2086  # one directory per word, by construction
    [ -n "$dirs" ] && run_tests $dirs --no-cov -q -x
    step bash scripts/floor_guard.sh
    protected=()
    while IFS= read -r g; do protected+=("$g"); done < <(protected_globs)
    unchanged_since_base "protected files" "${protected[@]}"
    ;;
  full)
    static_checks
    other_parts
    if [ "$TYPE_GATE" = mypy ]; then run pyright; else run mypy; fi
    # CR-41: the interface task's stubs and fields stay unused until later tasks use them.
    if [ ${#exit_check[@]} -gt 0 ]; then run vulture; else report vulture; fi
    run pylint --disable=all --enable=duplicate-code --recursive=y --score=n --fail-under=10 "${SRC_DIRS[@]}"   # CR-42
    run typos
    run pip-audit --skip-editable   # the external opinion: a vulnerability database (CR-26)
    step bash scripts/floor_guard.sh ${exit_check[@]+"${exit_check[@]}"}
    dirs=$(test_dirs)
    # Coverage threshold comes from [tool.coverage.report] fail_under (CR-40).
    # shellcheck disable=SC2086
    [ -n "$dirs" ] && HYPOTHESIS_PROFILE=ci run_tests $dirs --cov -q
    ;;
  protected)
    protected_globs
    ;;
  *)
    echo "unknown mode: $mode (fast | collect | gate | full | protected)" >&2
    exit 64
    ;;
esac
[ $rc -ne 0 ] && printf 'FAILED: %s\n' "${failed[@]}" >&2
exit $rc
